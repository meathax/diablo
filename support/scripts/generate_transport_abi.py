def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if checked-in generated files differ')
    args = parser.parse_args()
    spec = json.loads(SPEC_PATH.read_text(encoding='utf-8'))
    expected = {CPP_PATH: cpp(spec), SV_PATH: sv(spec)}
    stale = [path for path, text in expected.items() if not path.is_file() or path.read_text(encoding='utf-8') != text]
    if args.check:
        if stale:
            for path in stale:
                print(f'stale generated ABI output: {path.relative_to(ROOT)}', file=sys.stderr)
            return 1
        return 0
    for path, text in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
